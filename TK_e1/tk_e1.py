ventana = Tk()
ventana.config(bg="black")
ventana.iconbitmap("logo.ico")
ventana.geometry("500x500")
ventana.resizable(1,1)
ventana.title("Prieto's")



pantalla1 = Frame(ventana)
pantalla1.config(bd=30)
pantalla1.config(relief='sunken')
pantalla1.config(cursor='heart')
label = Label(pantalla1, text="¡Que tengas un buen día!")
label.place(x=450, y=30)
label.config(bg='brown')
label.config(font=('Serif', 20, 'bold',))
label.config(fg='white')
pantalla1.config(width=1250, height=300)
pantalla1.config(bg='blue')
pantalla1.pack()

pantalla2 = Frame(ventana)
pantalla2.config(width=650, height=300)
pantalla2.config(cursor='star')
label = Label(pantalla2, text="Que tinguis un bon dia!")
label.place(x=150, y=30)
label.config(bg='gold')
label.config(font=('Comic Sans MS', 20, 'bold',))
label.config(fg='white')
pantalla2.config(bg='magenta')
pantalla2.pack(side=LEFT)

pantalla3 = Frame(ventana)
pantalla3.config(width=650, height=300)
pantalla3.config(cursor='gumby')
label = Label(pantalla3, text="Have a nice day!")
label.place(x=200, y=30)
label.config(bg='white')
label.config(font=('Calibri', 20, 'bold',))
label.config(fg='black')
label.config(anchor='center')
pantalla3.config(bg='yellow')
pantalla3.pack(side=RIGHT)

imagen = PhotoImage(file="A1.png")
image_label = Label(pantalla1, image=imagen)
image_label.place(x=30, y=10)

imagen2 = PhotoImage(file="A2.png")
image_label2 = Label(pantalla2, image=imagen2)
image_label2.place(x=175, y=90)

imagen3 = PhotoImage(file="A3.png")
image_label3 = Label(pantalla3, image=imagen3)
image_label3.place(x=180, y=90)

ventana.mainloop()
